SELECT SAL*_DATE, COUNT(*) AS SALES_COUNT, SUM(QUANTITY) AS TOTAL_QUANTITY, SUM(AMOUNT) AS TOTAL_SALES FROM CURATED.SALES_CURATED GROUP BY SALE_DATE ORDER BY SALE_DATE;


