SALES_RAW VALIDATION QUERIES:

SELECT * FROM RAW.SALES_RAW ORDER BY SALE_ID;

--Total rows count
SELECT COUNT(*) AS RECORD_COUNT FROM RAW.SALES_RAW;

--Status Distribution
SELECT STATUS, COUNT(*) FROM RAW.SALES_RAW GROUP BY STATUS;

--Store-wise Distribution
SELECT STORE_ID, COUNT(*) FROM RAW.SALES_RAW GROUP BY STORE_ID ORDER BY STORE_ID;

--Duplicates check
SELECT SALE_ID, COUNT(*) FROM RAW.SALES_RAW GROUP BY SALE_ID HAVING COUNT(*) > 1;

--Null key-check validation
SELECT * FROM RAW.SALES_RAW WHERE SALE_ID IS NULL;

--Amount Summary
SELECT SUM(AMOUNT) AS TOTAL_AMOUNT FROM RAW.SALES_RAW;


